"""Single-producer live orchestration, gated by offline workflow verification.

The persistent stdin service preserves provider metadata and in-memory caches
while fresh actual Codex contexts service the exported public packets. No C
answer is generated by this program. Every paid nested call uses the aggregate.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

from .budget_guard import readonly_budget_snapshot
from .planning import HERE, ROOT, build_plan, load_config


OUT = ROOT / "runs/main/pressure_interview_live"
GATE = HERE / "WORKFLOW_GATE.json"


def source_files():
    return {str(p.relative_to(HERE)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(HERE.rglob("*")) if p.is_file()
            and p.suffix in {".py", ".txt"} and "tests" not in p.relative_to(HERE).parts
            and "__pycache__" not in p.parts}


def require_workflow_gate():
    if not GATE.is_file() or GATE.is_symlink():
        raise RuntimeError("Offline end-to-end workflow gate must pass before live initialization")
    gate = json.loads(GATE.read_text())
    config = load_config()
    encoded = json.dumps(config, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False).encode()
    if (gate.get("status") != "passed" or gate.get("source_files") != source_files()
            or gate.get("config_sha256") != hashlib.sha256(encoded).hexdigest()
            or gate.get("live_compatibility_probe_calls") != 0):
        raise RuntimeError("Workflow gate does not bind the current source/configuration")
    return gate


def coordinator(*, preflight=False):
    require_workflow_gate()
    from .live_provider import LiveOpenRouterBackend
    from .live_loss_policy import TransportContinuationGuard
    from .live_scheduler import StudyCoordinator
    config = load_config()
    guard = TransportContinuationGuard(ROOT / config["budget"]["aggregate_ledger"], config["budget"]["namespace"])
    backend = LiveOpenRouterBackend(guard, OUT / "provider_evidence", preflight=preflight)
    return StudyCoordinator(OUT, config=config, plan=build_plan(config), backend=backend,
                            budget_guard=guard, evidence_origin="live")


def emit(value):
    print(json.dumps(value, ensure_ascii=False, allow_nan=False), flush=True)


def _command(study, command):
    action = command.get("command")
    if action == "next":
        return study.advance()
    if action == "mark":
        study.mark_codex_dispatched(command["job_id"], command["reviewer_agent"])
        return {"status": "codex_dispatch_recorded", "job_id": command["job_id"]}
    if action == "import":
        raw_path = Path(command["raw_answer_path"])
        if not raw_path.is_file() or raw_path.is_symlink():
            raise ValueError("The original observed answer file is required")
        result = study.import_codex_response(command["job_id"], raw_path.read_text(), command["provenance"])
        if command.get("advance", True):
            return {"import_result": result, "next": study.advance()}
        return {"import_result": result}
    if action == "summary":
        return study.summary()
    if action == "budget":
        return readonly_budget_snapshot(ROOT / study.config["budget"]["aggregate_ledger"])
    if action == "quit":
        return {"status": "service_stopped_no_new_requests"}
    raise ValueError("Unknown orchestration command")


def serve():
    # This preflight uses GET metadata only. Inference begins only in next().
    study = coordinator(preflight=True)
    emit({"event": "ready", "status": "workflow_verified_free_preflight_passed",
          "budget": readonly_budget_snapshot(ROOT / study.config["budget"]["aggregate_ledger"]),
          "next": study.advance()})
    for line in sys.stdin:
        if not line.strip():
            continue
        command = None
        try:
            command = json.loads(line)
            if not isinstance(command, dict):
                raise ValueError("Orchestration command must be an object")
            result = _command(study, command)
            emit({"event": "result", "command": command.get("command"), "result": result})
            if command.get("command") == "quit":
                break
        except Exception as error:
            # No provider/error body or environment values reach the terminal.
            emit({"event": "error", "exception_class": type(error).__name__,
                  "no_automatic_retry": True, "inspect_retained_records": True})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("serve", "status", "budget", "preflight", "advance", "verify", "report", "export"))
    parser.add_argument("--destination", type=Path)
    args = parser.parse_args()
    if args.command == "serve":
        serve()
    elif args.command == "budget":
        emit(readonly_budget_snapshot(ROOT / load_config()["budget"]["aggregate_ledger"]))
    elif args.command == "status":
        path = OUT / "run_status.json"
        emit(json.loads(path.read_text()) if path.exists() else {"status": "not_started"})
    elif args.command == "preflight":
        study = coordinator(preflight=True)
        emit({"status": "free_preflight_passed", "live_paid_requests_made_by_preflight": 0,
              "summary": study.summary()})
    elif args.command == "verify":
        from .live_analysis import verify_study
        emit(verify_study(OUT))
    elif args.command == "report":
        from .live_analysis import build_report
        result = build_report(OUT)
        emit({"status": "report_written", "path": str(OUT / "analysis/report.json"),
              "counts": result.get("counts", {})})
    elif args.command == "export":
        from .live_analysis import export_study
        destination = args.destination or ROOT.parent / "image_collusion_pressure_interview_results.zip"
        emit(export_study(OUT, destination))
    else:
        emit(coordinator(preflight=True).advance())


if __name__ == "__main__":
    main()
